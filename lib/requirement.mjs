/**
 * 요구사항 **미충족**을 잡는다 — 충족은 못 잰다.
 *
 * ⛔ R23·R08 이 남긴 자리: 「게이트가 재는 것은 lint·build·test 다. **요구사항 충족은
 * 사람이 봐야 한다**」. 그래서 3차 팽창의 산출물은 **아무도 요구사항과 대조하지 않았다.**
 *
 * ⚠️⚠️ **이 검사는 한쪽만 잰다.** 통과해도 **충족을 뜻하지 않는다** — 낱말이 있다고 동작하는
 * 것은 아니다. 실패하면 **확실히 안 했다**는 뜻이다(요구사항의 알맹이 낱말이 코드 어디에도 없다).
 * 그래서 이름이 `unmetSignals` 다 — 「충족했는가」가 아니라 「**안 한 흔적이 있는가**」.
 *
 * ⚠️ 낱말을 **열거하지 않는다**(§9). 조사·기능어를 빼는 대신, **길이와 반복**으로 알맹이를
 * 고른다 — 두 글자 이상이고 요구사항에서 한 번만 나오는 명사류가 알맹이일 확률이 높다.
 *
 * 재는 법: `node lib/selftest.mjs`
 */

/** 조사·어미가 붙은 한국어 낱말의 앞부분. `배지를` → `배지` */
const stem = (word) => word.replace(/(?:을|를|이|가|은|는|에|의|로|으로|와|과|도|만|까지|부터|에서|에게|한다|하라|해라|하고|하며|한|할|하는)$/u, '');

/**
 * @param {string} requirement 요구사항 한 줄
 * @param {string} produced    만들어진 코드 전부(파일들을 이어 붙인 것)
 * @returns {string[]|null} 코드 어디에도 흔적이 없는 알맹이 낱말들. 비면 **미충족 흔적이 없다**는 뜻이다.
 *   `null` 이면 **못 잰다**(영어 등 — 알맹이와 기능어를 가를 손잡이가 없다).
 */
export const unmetSignals = (requirement, produced) => {
  const haystack = produced.toLowerCase();
  const seen = new Map();
  for (const raw of requirement.split(/[^\p{L}\p{N}]+/u)) {
    const word = stem(raw);
    /* ⚠️ 한 글자는 알맹이가 아니다. 숫자만인 것도 아니다. */
    if (word.length < 2 || /^\p{N}+$/u.test(word)) {
      continue;
    }
    /* ⛔ **영어는 이 신호로 못 잰다(R131 실측).** 한국어는 어미로 동사를 가를 수 있지만
       영어는 그 손잡이가 없다 — 제대로 만든 코드에도 `the`·`and`·`when` 이 「안 했다」로 나왔다
       (알맹이 12개 중 6개가 오탐). **기능어를 열거하면 §9 이고, 안 열거하면 못 가른다.**
       ⇒ **못 재는 것은 못 잰다고 말한다.** 조용히 나쁜 신호를 내는 것보다 낫다(§8). */
    if (/^[A-Za-z]+$/u.test(word)) {
      return null;
    }
    /* ⛔ **동사는 알맹이가 아니다(실측).** 첫 판은 `보여`·`주고`·`띄워라` 를 「안 했다」로 셌다 —
       요구사항의 절반이 오탐이었다. 코드에 남는 것은 **이름**이지 동작 서술이 아니다.
       ⚠️ 어미로 가른다 — 낱말을 열거하는 것이 아니다(§9). */
    if (/(?:다|라|자|고|서|며|면|여|워|줘|해|게|지|어|아|되|하)$/u.test(word)) {
      continue;
    }
    seen.set(word, (seen.get(word) ?? 0) + 1);
  }
  return [...seen.keys()].filter((word) => !haystack.includes(word.toLowerCase()));
};
