/**
 * **은하가 서는가** — 재기 전에 먼저 본다.
 *
 * ⚠️⚠️ 왜 이 칸이 따로 있는가(R149). R146 이 신호를 셋으로 갈랐다:
 *   · ✅ 잰 초록  · ❌ 잰 빨강  · ⚪ **못 쟀다**
 * 그런데 R148 에서 넷째가 드러났다 — **은하가 아예 안 서는 경우**다.
 *
 * 실측: `backoffice` 의 `.yarnrc.yml` 은 `${NODE_AUTH_TOKEN}` 을 참조한다. 그 변수가 없으면
 * **yarn 이 어떤 명령도 안 돈다** — `yarn build` 가 0.2초 만에 죽고, `yarn exec eslint` 도
 * 같이 죽어 lint JSON 이 아예 안 생긴다. 그 상태로 3차를 태우면:
 *   1차가 별을 쓰고 → 컴파일 관문이 「못 쟀다」로 넘어가고 → **모델을 턴 수만큼 부르고** →
 *   게이트가 전부 깨진 채 빨간불을 돌려주고 → 에이전트가 못 고치는 것을 고치려 든다.
 * ⇒ **못 잴 것이 뻔한 곳에 사용량을 쓴다.** 「못 쟀다」는 정직하지만 **너무 늦다.**
 *
 * ⛔ 이것은 「못 쟀다」의 또 다른 이름이 아니다. 셋과 다른 **넷째 판정**이다:
 *   · 주행 **전**  · 선언한 필수 환경변수가 없다 → **「은하가 안 선다」** ← 여기
 *   · 주행 **중**  · 명령을 선언 안 했거나 도구가 없다 → ⚪ 못 쟀다
 *   · 주행 **중**  · 도구가 돌았고 빨간불 → ❌ 별 탓 / 은하 탓
 *
 * ⛔ **변수 이름을 우주가 열거하지 않는다**(§9). 무엇이 필요한지는 **은하가 선언한다** —
 *    `requiredEnv` 가 없는 은하에서는 이 검사가 아무것도 하지 않는다(옵트인).
 * ⛔ **값을 읽지 않는다.** 있는지만 본다 — 비밀은 우리가 볼 것이 아니고, 봤다고 적으면
 *    로그에 새어 나간다.
 */

/**
 * @param {{requiredEnv?: string[]}} galaxy 은하 좌표
 * @param {Record<string,string|undefined>} env 볼 환경(보통 `process.env`)
 * @returns {string[]} 비어 있거나 없는 변수 이름들. 비면 **은하가 선다**.
 */
export const missingEnv = (galaxy, env) => {
  const declared = galaxy?.requiredEnv;
  /* 옵트인 — 선언 안 한 은하는 이 검사가 **아무것도 하지 않는다.** */
  if (declared === undefined || declared === null) {
    return [];
  }
  /* ⛔ 선언이 배열이 아니면 **막지 않는다.** 좌표 오타로 은하 전체를 세우면,
     받는 사람은 도구가 깨진 줄 안다(R58) — 여기서 막을 일이 아니라 형식 검사가 할 일이다. */
  if (!Array.isArray(declared)) {
    return [];
  }
  /* ⚠️ 빈 문자열도 **없는 것**이다. `FOO=` 로 둔 채 「넣었다」고 하는 자리가 실제로 있다
     (같은 패턴을 쓴 다른 저장소가 세 키 중 둘을 `${FOO:-}` 빈 기본값으로 뒀다 — 실측). */
  return declared.filter((name) => typeof name === 'string' && name !== '' && !env[name]);
};

/**
 * 사람에게 보일 문장. **무엇을 해야 하는지까지** 적는다 —
 * 「없다」만 말하면 받는 사람은 은하가 깨진 줄 안다(R58 이 겪은 그것).
 */
export const cannotStandMessage = (galaxyName, missing) =>
  [
    `⛔ **은하 ${galaxyName} 가 서지 않는다** — 좌표가 요구한 환경변수 ${missing.length}개가 비어 있다:`,
    ...missing.map((name) => `     · ${name}`),
    '',
    '   이것은 「못 쟀다」가 아니다 — **재기 시작할 수도 없다는 뜻**이다.',
    '   이 상태로는 은하의 도구 사슬이 통째로 안 돌아, 게이트가 전부 깨진 채 빨간불을 낸다.',
    '   ⛔ 그래서 여기서 멈춘다 — 못 잴 것이 뻔한 곳에 별을 쓰거나 모델을 부르지 않는다.',
    '',
    `   채우고 다시 불러라. 무엇이 왜 필요한지는 좌표(galaxies/${galaxyName}.json)의 \`//환경\` 에 적혀 있다.`,
  ].join('\n');
